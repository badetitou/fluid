/** Every package's classes and their methods, with the counts the pyramid adds up. */
const packageMetrics = /* GraphQL */ `
  query FluidOverviewPyramid($id: ID!) {
    package(id: $id) {
      id
      name
      childPackages {
        id
      }
      classes {
        id
        fanOut
        hierarchyNestingLevel
        subclasses {
          id
        }
        methods {
          id
          linesOfCode
          cyclomaticComplexity
          outgoingInvocations {
            id
          }
        }
      }
    }
  }
`;

