import { z } from 'zod';
import type { ViewSpec } from '../view-spec';
import { dataBindingSchema, widgetBase } from './common';

/**
 * Where a metric of the pyramid is read: a dot path to a number in the bound
 * object (e.g. "numberOfClasses"), or an aggregate over a list of it:
 * `{ rows?, op, field? }`. `rows` is a dot path to the list (crossing nested
 * lists flattens them: "classes.methods" is every method of every class);
 * omitted, the bound data itself (a list) is used. `count` counts the rows;
 * `sum` / `avg` add up / average `field` over them, a list-valued field
 * counting its items (`field: "subclasses"` → the number of subclasses).
 */
export const pyramidMetricSchema = z.union([
  z.string().min(1),
  z
    .object({
      rows: z.string().min(1).optional(),
      op: z.enum(['count', 'sum', 'avg']),
      field: z.string().min(1).optional(),
    })
    .refine((m) => m.op === 'count' || m.field, { message: 'sum and avg need a "field"', path: ['field'] }),
]);
export type PyramidMetric = z.infer<typeof pyramidMetricSchema>;

/** The metrics of the pyramid, in the order of the figure. */
export const PYRAMID_METRICS = ['nop', 'noc', 'nom', 'loc', 'cyclo', 'calls', 'fanout', 'andc', 'ahh'] as const;
export type PyramidMetricKey = (typeof PYRAMID_METRICS)[number];

/** The values colored low / average / high: the six ratios, ANDC and AHH. */
export const PYRAMID_RATIOS = ['nocNop', 'nomNoc', 'locNom', 'cycloLoc', 'callsNom', 'fanoutCalls', 'andc', 'ahh'] as const;
export type PyramidRatioKey = (typeof PYRAMID_RATIOS)[number];

/** Reference values of a ratio: low, average and high. A value takes the level it is closest to. */
const thresholdTriple = z
  .tuple([z.number(), z.number(), z.number()])
  .refine(([l, a, h]) => l <= a && a <= h, 'Thresholds go low ≤ average ≤ high');

const metricFields = Object.fromEntries(PYRAMID_METRICS.map((key) => [key, pyramidMetricSchema.optional()])) as {
  [K in PyramidMetricKey]: z.ZodOptional<typeof pyramidMetricSchema>;
};

/**
 * The Overview Pyramid (Lanza & Marinescu): a system or a package summed up in
 * one figure. Size & complexity on the left (NOP, NOC, NOM, LOC, CYCLO, in
 * steps), coupling on the right (CALLS, FANOUT), inheritance on top (ANDC,
 * AHH), the raw values and the ratios between neighbours colored low / average
 * / high against reference thresholds. A metric left out leaves its brick empty.
 */
const pyramidWidgetShape = z.object({
  type: z.literal('pyramid'),
  ...widgetBase,
  /** The object carrying the metrics (a model, a package), or a list the metrics are aggregated from. */
  data: dataBindingSchema,
  /** Number of packages. */
  nop: metricFields.nop,
  /** Number of classes. */
  noc: metricFields.noc,
  /** Number of methods (operations). */
  nom: metricFields.nom,
  /** Lines of code (of the methods). */
  loc: metricFields.loc,
  /** Sum of the cyclomatic complexities of the methods. */
  cyclo: metricFields.cyclo,
  /** Number of method calls (distinct operation calls). */
  calls: metricFields.calls,
  /** Sum of the classes' fan-out (classes called). */
  fanout: metricFields.fanout,
  /** Average number of direct subclasses per class. */
  andc: metricFields.andc,
  /** Average hierarchy height (depth of inheritance) per class. */
  ahh: metricFields.ahh,
  /** Reference thresholds set (default "java", those of the book; "smalltalk" for Pharo code, "cpp"). */
  thresholdPreset: z.enum(['java', 'cpp', 'smalltalk']).optional(),
  /** Per ratio, `[low, average, high]` overriding the preset (keys: nocNop, nomNoc, locNom, cycloLoc, callsNom, fanoutCalls, andc, ahh). */
  thresholds: z
    .object(Object.fromEntries(PYRAMID_RATIOS.map((key) => [key, thresholdTriple.optional()])) as {
      [K in PyramidRatioKey]: z.ZodOptional<typeof thresholdTriple>;
    })
    .optional(),
});

const NO_METRIC = 'Set at least one metric (nop, noc, nom, loc, cyclo, calls, fanout, andc, ahh)';
const hasMetric = (w: Partial<Record<PyramidMetricKey, unknown>>) => PYRAMID_METRICS.some((key) => w[key] != null);

export const pyramidWidgetSchema = pyramidWidgetShape.refine(hasMetric, { message: NO_METRIC, path: ['noc'] });
export type PyramidWidget = z.infer<typeof pyramidWidgetSchema>;

/** The pyramid as generated by the LLM, without its id (zod cannot omit from a refined object). */
export const pyramidWidgetDraftSchema = pyramidWidgetShape
  .omit({ id: true })
  .refine(hasMetric, { message: NO_METRIC, path: ['noc'] });

