import { z } from 'zod';
import type { ViewSpec } from '../view-spec';
import { dataBindingSchema, linkToSchema, widgetBase } from './common';

/**
 * A polymetric view (Lanza): one box per row, its width, height and color
 * mapped to up to three metrics, laid out as a hierarchy (`tree`, e.g. the
 * System Complexity of classes and their superclass), as boxes flowing in
 * titled frames, one per container (`flow`, e.g. a distribution map of classes
 * per package), or as a treemap nesting containers (`treemap`). Hovering a box
 * shows its metrics; clicking it selects it (emitted on `selected`) and opens
 * it in a new column. The canvas zooms with the wheel and pans by dragging.
 */
const boxesWidgetShape = z.object({
  type: z.literal('boxes'),
  ...widgetBase,
  /** The boxes: one per row. */
  data: dataBindingSchema,
  /** Dot path of a box's id, unique across the rows (default "id"); also read in parent objects. */
  idField: z.string().min(1).optional(),
  /** Dot path of a box's name (default: name, title, label… whichever the row has). */
  labelField: z.string().min(1).optional(),
  /** Dot path of a numeric metric giving the box's width (default: a fixed width). */
  widthField: z.string().min(1).optional(),
  /** Dot path of a numeric metric giving the box's height (default: a fixed height). */
  heightField: z.string().min(1).optional(),
  /** Dot path of a numeric metric giving the box's area: in a treemap, or a square box when no width/height. */
  sizeField: z.string().min(1).optional(),
  /** Dot path of the value coloring the box: a metric (light to dark) or a category (palette and legend). */
  colorField: z.string().min(1).optional(),
  /** How `colorField` is read (default: `sequential` when every value is a number, else `categorical`). */
  colorScale: z.enum(['sequential', 'categorical']).optional(),
  /**
   * Dot path of the box's parent: its id, or an object (or list of objects, first one kept) holding it,
   * e.g. "superclass.id" or "superclass". Draws a hierarchy.
   */
  parentField: z.string().min(1).optional(),
  /** Dot path of the box's container (e.g. "parentPackage.name"): boxes grouped in titled frames. */
  groupField: z.string().min(1).optional(),
  /**
   * How boxes are placed (not `layout`, which every widget uses for its grid placement): `tree` (needs
   * `parentField`), `flow`, or `treemap` (areas from `sizeField`, nesting groups and children).
   * Default: `tree` with a `parentField`, else `flow`.
   */
  boxLayout: z.enum(['tree', 'flow', 'treemap']).optional(),
  /** Hovering a box highlights the boxes of its group (default true when `groupField` is set). */
  highlightGroup: z.boolean().optional(),
  /** Opens the clicked box in a new column. */
  linkTo: linkToSchema.optional(),
});

type BoxesShape = z.infer<typeof boxesWidgetShape>;

const TREE_MESSAGE = 'A "tree" layout needs the hierarchy: set "parentField" (e.g. "superclass.id"), or use "flow".';
const COLOR_MESSAGE = '"colorScale" says how "colorField" is read: set "colorField".';

const treeHasParent = (w: Pick<BoxesShape, 'boxLayout' | 'parentField'>) => w.boxLayout !== 'tree' || w.parentField !== undefined;
const scaleHasField = (w: Pick<BoxesShape, 'colorScale' | 'colorField'>) => w.colorScale === undefined || w.colorField !== undefined;

export const boxesWidgetSchema = boxesWidgetShape
  .refine(treeHasParent, { message: TREE_MESSAGE, path: ['parentField'] })
  .refine(scaleHasField, { message: COLOR_MESSAGE, path: ['colorField'] });
export type BoxesWidget = z.infer<typeof boxesWidgetSchema>;

/** The boxes widget as generated by the LLM, without its id (zod cannot omit from a refined object). */
export const boxesWidgetDraftSchema = boxesWidgetShape
  .omit({ id: true })
  .refine(treeHasParent, { message: TREE_MESSAGE, path: ['parentField'] })
  .refine(scaleHasField, { message: COLOR_MESSAGE, path: ['colorField'] });

/** How the LLM is told to use the boxes widget. */
export const boxesWidgetDoc = `- { "id": string, "type": "boxes", "title"?: string, "span"?: 1..24, "height"?: number,
    "data": { "query": ..., "path"?: ... }, "idField"?: string, "labelField"?: string, "widthField"?: string,
    "heightField"?: string, "sizeField"?: string, "colorField"?: string, "colorScale"?: "sequential"|"categorical",
    "parentField"?: string, "groupField"?: string, "boxLayout"?: "tree"|"flow"|"treemap",
    "highlightGroup"?: boolean, "linkTo"?: LinkConfig }
    A POLYMETRIC VIEW: one box per row, comparing items on 2-3 metrics at once (box width, height, color)
    together with their hierarchy or their container. The canonical case: classes as boxes, width = number of
    attributes, height = number of methods, color = lines of code, under their superclass (System Complexity).
    Also: packages by size and complexity, modules per layer, files per folder, services per team…
    Prefer it to "scatter" when the hierarchy or the container matters, to "network" for metrics over links.
    - "widthField"/"heightField"/"sizeField": NUMERIC fields (e.g. "numberOfAttributes", "numberOfMethods");
      count a nested list with a transform first: \`"transform": { "derive": [{ "as": "methodCount", "op": "count",
      "field": "methods" }] }\` then "heightField": "methodCount". Omitted → fixed size.
    - "colorField": a metric (light→dark, min/max legend) or a category such as a kind or a package (palette,
      legend); "colorScale" forces the reading.
    - "parentField" → "boxLayout": "tree" (the default then): each box under its parent, orthogonal edges
      (e.g. "superclass.id", or "superInheritances.superclass" for association objects; select the parent's id).
    - "groupField" (e.g. "parentPackage.name") → "flow" boxes in one titled frame per group (distribution map,
      architectural map); hovering a box highlights its group.
    - "boxLayout": "treemap": areas from "sizeField" (e.g. "numberOfLinesOfCode"), groups and children nested.
    Up to 2000 boxes: filter or limit the query beyond. Set "linkTo" whenever rows have an id. Clicking a box
    emits its row on "selected" (bind a "descriptions" to \`{ "query": "@<id>", "path": "selected" }\`).`;

