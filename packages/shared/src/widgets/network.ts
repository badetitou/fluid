import { z } from 'zod';
import type { ViewSpec } from '../view-spec';
import { columnSchema, dataBindingSchema, linkToSchema, widgetBase } from './common';

/**
 * A node-link diagram for thousands of items linked to each other: class
 * dependencies, call graphs, items and what they reference… Drawn with WebGL,
 * zoomable and pannable; hovering a node shows its card and highlights its
 * neighbours, clicking it selects it (opens it in a new column, emits it on
 * `selected`), and the view can focus on the neighbourhood of the selection.
 *
 * Nodes are the bound rows. Edges are directed, deduplicated, without loops,
 * and come either from edge rows (`edges`) or from a list in each node
 * (`linksField`). A link whose end is not among the nodes adds that end as a
 * node (`missingNodes: "add"`, the default) — built from the linked object when
 * the link is an object — or drops the edge (`"ignore"`).
 */
const networkWidgetShape = z.object({
  type: z.literal('network'),
  ...widgetBase,
  /** The nodes. */
  data: dataBindingSchema,
  /** Dot path of a node's id, unique across every node (default "id"); also read in linked objects. */
  idField: z.string().min(1).optional(),
  /** Dot path of a node's text (default: name, title, label… whichever the row has). */
  labelField: z.string().min(1).optional(),
  /** Dot path of a node's kind (class, method…): colors the nodes and picks `linkToByGroup`. */
  groupField: z.string().min(1).optional(),
  /** Numeric field scaling the nodes (default: their number of links). */
  sizeField: z.string().min(1).optional(),
  /** Lines shown under the label on hover (default: the group). */
  tooltipFields: z.array(columnSchema).optional(),
  /** Edge rows (one per link), when the nodes do not list their links. */
  edges: dataBindingSchema.optional(),
  /** Dot path of an edge's source id, or of an object holding it (default "source"). */
  sourceField: z.string().min(1).optional(),
  /** Dot path of an edge's target id, or of an object holding it (default "target"). */
  targetField: z.string().min(1).optional(),
  /**
   * Dot path of a list in each node: the ids (or objects holding the id) it points to, possibly through
   * association objects ("superInheritances.superclass"). Linked objects' own links are followed at any depth.
   */
  linksField: z.string().min(1).optional(),
  /** Links to items that are not nodes: added as nodes (default) or ignored. */
  missingNodes: z.enum(['add', 'ignore']).optional(),
  /**
   * How nodes are placed: `force` (default), clusters emerge; `layered`, links flow in one direction.
   * (Not `layout`, which every widget uses for its grid placement.)
   */
  graphLayout: z.enum(['force', 'layered']).optional(),
  /** Direction of a layered layout: top to bottom (default) or left to right. */
  direction: z.enum(['TB', 'LR']).optional(),
  /** Levels of neighbours kept around the selection when focusing on it (default 2). */
  focusDepth: z.number().int().min(1).max(10).optional(),
  /** Which links the focus follows: incoming, outgoing or both (default). */
  focusDirection: z.enum(['in', 'out', 'both']).optional(),
  /** Opens the clicked node in a new column. */
  linkTo: linkToSchema.optional(),
  /** Per value of `groupField`, how to open its nodes; takes precedence over `linkTo`. */
  linkToByGroup: z.record(z.string(), linkToSchema).optional(),
});

type NetworkShape = z.infer<typeof networkWidgetShape>;

const EDGES_MESSAGE =
  'A network needs its links: set "edges" (a binding to edge rows, with "sourceField"/"targetField") or "linksField" (a list in each node).';
const GROUP_MESSAGE = '"linkToByGroup" picks a link by the value of "groupField": set "groupField".';

const hasEdges = (w: Pick<NetworkShape, 'edges' | 'linksField'>) => w.edges !== undefined || w.linksField !== undefined;
const groupsLinks = (w: Pick<NetworkShape, 'linkToByGroup' | 'groupField'>) =>
  w.linkToByGroup === undefined || w.groupField !== undefined;

export const networkWidgetSchema = networkWidgetShape
  .refine(hasEdges, { message: EDGES_MESSAGE, path: ['linksField'] })
  .refine(groupsLinks, { message: GROUP_MESSAGE, path: ['groupField'] });
export type NetworkWidget = z.infer<typeof networkWidgetSchema>;

/** The network widget as generated by the LLM, without its id (zod cannot omit from a refined object). */
export const networkWidgetDraftSchema = networkWidgetShape
  .omit({ id: true })
  .refine(hasEdges, { message: EDGES_MESSAGE, path: ['linksField'] })
  .refine(groupsLinks, { message: GROUP_MESSAGE, path: ['groupField'] });

/** How the LLM is told to use the network widget. */
export const networkWidgetDoc = `- { "id": string, "type": "network", "title"?: string, "span"?: 1..24, "height"?: number,
    "data": { "query": ..., "path"?: ... }, "idField"?: string, "labelField"?: string, "groupField"?: string,
    "sizeField"?: string, "tooltipFields"?: [ Column, ... ],
    "linksField"?: string, "edges"?: DataBinding, "sourceField"?: string, "targetField"?: string,
    "missingNodes"?: "add"|"ignore", "graphLayout"?: "force"|"layered", "direction"?: "TB"|"LR",
    "focusDepth"?: number, "focusDirection"?: "in"|"out"|"both",
    "linkTo"?: LinkConfig, "linkToByGroup"?: { "<group value>": LinkConfig, ... } }
    Use it for ITEMS LINKED TO EACH OTHER, many-to-many, possibly thousands: class or package dependencies,
    call graphs (methods → methods they call), imports between modules, characters ↔ episodes, people who
    follow each other… Prefer "tree" for a pure hierarchy, "classDiagram" for inheritance (superclasses)
    and "history" for versions. The bound rows are the NODES. The links (directed, at least one form):
    * "linksField": a list in each node, of ids or of objects holding the id (e.g. \`dependencies { id }\`
      → "dependencies", \`calls { id name }\` → "calls"); linked objects that are not nodes become nodes
      (built from their selected fields), unless "missingNodes": "ignore". Links are FOLLOWED AT ANY DEPTH:
      a linked object that selects the same list again adds its own links, and so on (to draw a call graph
      over N levels, nest \`calls { id name calls { id name calls { … } } }\` N times). When the list holds
      association objects rather than the linked items (e.g. \`superInheritances { superclass { id } }\`),
      point at the item through them with a dot path: "superInheritances.superclass" (nesting
      \`superclass { id name superInheritances { superclass { … } } }\` walks up the whole hierarchy);
    * "edges": a second binding to edge rows, with "sourceField"/"targetField" (default source/target;
      ids or objects holding the id, e.g. \`calls { caller { id } callee { id } }\`).
    "idField" must be UNIQUE ACROSS ALL NODES: GraphQL ids are often unique per type only, so when types
    are mixed pick a globally unique field (qualified name, path…). Set "groupField" to the kind of node
    (e.g. "__typename", "kind") to color nodes; nodes of different kinds open different concepts: set
    "linkToByGroup" (keyed by the group values) and/or "linkTo" — always set one when nodes have an id.
    "graphLayout": "layered" (with "direction") for dependency flows on small graphs, "force" otherwise. The
    user can focus on the clicked node: "focusDepth" levels of neighbours following "focusDirection".
    Clicking a node emits its row on "selected".`;

