import { z } from 'zod';
import type { ViewSpec } from '../view-spec';
import { dataBindingSchema, widgetBase } from './common';

/**
 * An AI analysis of the view: once the other widgets have their data, the
 * widget sends what they show to the LLM (through the BFF) and renders what it
 * found beyond the obvious: anomalies, concentrations, correlations across
 * widgets, data gaps, questions worth asking next. When there is nothing more
 * to say, it just says hello.
 */
const insightWidgetShape = z.object({
  type: z.literal('insight'),
  ...widgetBase,
  /** Extra data to analyse besides the other widgets (e.g. a query no widget shows). */
  data: dataBindingSchema.optional(),
  /** Ids of the widgets to analyse (default: every other widget of the view). */
  sources: z.array(z.string().min(1)).max(20).optional(),
  /** The angle of the analysis, in the user's words (e.g. "where is the money going?"). */
  focus: z.string().min(1).max(500).optional(),
});

export const insightWidgetSchema = insightWidgetShape;
export type InsightWidget = z.infer<typeof insightWidgetSchema>;

/** The insight widget as generated by the LLM, without its id. */
export const insightWidgetDraftSchema = insightWidgetShape.omit({ id: true });

/** How the LLM is told to use the insight widget. */
export const insightWidgetDoc = `- { "id": string, "type": "insight", "title"?: string, "span"?: 1..24,
    "sources"?: ["<widget id>", ...], "focus"?: string, "data"?: { "query": ..., "path"?: ... } }
    An AI ANALYST of the view: once the other widgets have loaded, it reads their data and writes an in-depth
    analysis (anomalies, concentrations, correlations across widgets, data gaps, questions to dig into next).
    Add at most one per view, usually full width ("span": 24) at the bottom, when the user asks for insights,
    an analysis, a summary or "what stands out". "sources" restricts it to some widgets (default: all the
    others); "focus" gives the angle, in the user's words; "data" adds a query no widget shows. It never
    replaces the widgets that show the data.`;

/** A curated view on the Rick and Morty API: characters, their split by species, and an AI analysis. */
