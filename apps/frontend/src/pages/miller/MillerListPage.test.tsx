/**
 * Regression tests for the dashboard URL round trip (issue #29).
 *
 * React Router decodes its splat param and turns an id's `%2F` into a real
 * `/`. The page must read the still-encoded `location.pathname` instead, or a
 * key such as a SCIP id opens one bogus column per fragment of the key.
 */

import { cleanup, render, screen } from '@testing-library/react';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { MemoryRouter, Route, Routes } from 'react-router-dom';
import type { ColumnConfig } from './model';

vi.mock('../../entities/dashboard', () => ({
  useDashboards: () => ({ find: () => undefined }),
}));
vi.mock('./MillerListView', () => ({
  MillerListView: ({ columns }: { columns: ColumnConfig[] }) => (
    <div data-testid="columns">
      {JSON.stringify(columns.map(({ conceptName, itemId }) => ({ conceptName, itemId })))}
    </div>
  ),
}));

import { MillerListPage } from './MillerListPage';

const key = 'model java . . java/lang/String#`<init>`().';
// The href generated by `appendColumn` for a row's key, as seen in the browser.
const href = `/d/Constructor/Constructor@${encodeURIComponent(key)}`;

afterEach(cleanup);

function columns() {
  return JSON.parse(screen.getByTestId('columns').textContent ?? '[]') as { conceptName: string; itemId?: string }[];
}

describe('MillerListPage URL parsing', () => {
  it('opens one detail column with the unchanged key, not one column per path fragment', () => {
    render(
      <MemoryRouter initialEntries={[href]}>
        <Routes>
          <Route path="/d/*" element={<MillerListPage />} />
        </Routes>
      </MemoryRouter>,
    );

    // Exactly one new column, introspected as `Constructor` (so no
    // "Unknown concept" for `lang` or `String#…`), with the query's `id`.
    expect(columns()).toEqual([
      { conceptName: 'Constructor' },
      { conceptName: 'Constructor', itemId: key },
    ]);
  });

  it('still opens a simple key in one column', () => {
    render(
      <MemoryRouter initialEntries={['/d/Character/Character@1']}>
        <Routes>
          <Route path="/d/*" element={<MillerListPage />} />
        </Routes>
      </MemoryRouter>,
    );

    expect(columns()).toEqual([{ conceptName: 'Character' }, { conceptName: 'Character', itemId: '1' }]);
  });
});
